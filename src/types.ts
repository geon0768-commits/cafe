// 음료 메뉴 아이템 타입 정의
export interface BeverageItem {
  id: string;
  name: string;
  price: number;
}

// 사이즈 옵션 타입 정의
export interface SizeOption {
  id: 'S' | 'M' | 'L';
  name: string;
  extraPrice: number;
}

// 추가 옵션 타입 정의
export interface ExtraOption {
  id: string;
  name: string;
  price: number;
}

// 주문서 폼 상태 인터페이스
export interface OrderFormData {
  customerName: string;      // 1. 주문자 이름 (필수)
  phoneNumber: string;       // 2. 전화번호
  beverageId: string;        // 3. 선택된 음료 ID
  size: 'S' | 'M' | 'L';     // 4. 사이즈 (기본값 M)
  extraOptionIds: string[];  // 5. 선택된 추가 옵션 ID 목록
  quantity: number;          // 6. 주문 수량 (기본값 1, 1~10)
  requests: string;          // 7. 요청사항
}

// 접수된 주문 기록 인터페이스
export interface OrderRecord {
  id: string;
  customerName: string;
  phoneNumber: string;
  beverageName: string;
  sizeName: string;
  extraOptionsSummary: string;
  quantity: number;
  requests: string;
  totalPrice: number;
  confirmationMessage: string;
  orderedAt: string;
}

