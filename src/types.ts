// Supabase SQL Editor에 복사할 테이블 및 정책 설정
export const SUPABASE_SQL_SCRIPT = `
CREATE TABLE IF NOT EXISTS public.cafe_menu (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name VARCHAR(100) NOT NULL,
  phone_number VARCHAR(30),
  beverage_name VARCHAR(100) NOT NULL,
  size_option VARCHAR(10) NOT NULL DEFAULT 'M',
  extra_options TEXT[] NOT NULL DEFAULT '{}',
  quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity BETWEEN 1 AND 10),
  requests TEXT,
  total_price INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.cafe_menu ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, DELETE ON public.cafe_menu TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.cafe_menu_id_seq TO anon, authenticated;

DROP POLICY IF EXISTS "Public can read cafe orders" ON public.cafe_menu;
CREATE POLICY "Public can read cafe orders"
  ON public.cafe_menu FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "Public can create cafe orders" ON public.cafe_menu;
CREATE POLICY "Public can create cafe orders"
  ON public.cafe_menu FOR INSERT TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "Public can clear cafe orders" ON public.cafe_menu;
CREATE POLICY "Public can clear cafe orders"
  ON public.cafe_menu FOR DELETE TO anon, authenticated USING (true);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime'
      AND schemaname = 'public'
      AND tablename = 'cafe_menu'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.cafe_menu;
  END IF;
END $$;
`;
